"""
example.py  --  Reproduce Example 1 from the paper (Section 4.1).

Tree structure (Fig. 1 / Fig. LNCCV in the paper):
  V = {v1, v2, ..., v10}  (indexed 0..9 internally)
  E = {e2, ..., e10}       (9 edges for 10-node tree)

  The paper uses 1-indexed node names v1..v10.
  We map: v_i  ->  index i-1  (so v1=0, v2=1, ..., v10=9).

Edges and weights derived from Table 1 in the paper:
  e2  = (v1, v2):  w=6,  u=10
  e3  = (v2, v3):  w=7,  u=10   [Table 1: g(chi_v3,0,0)=7, so w(e3)=7]
  e4  = (v2, v4):  w=4,  u=10
  e5  = (v1, v5):  w=1,  u=10   [Table 1: g(chi_v6,1,1)=18 requires Dw(e5)=9]
  e6  = (v5, v6):  w=8,  u=10   [v6 is a leaf; w(e5)+w(e6)=9]
  e7  = (v1, v7):  w=4,  u=10
  e8  = (v7, v8):  w=3,  u=10
  e9  = (v7, v9):  w=4,  u=10
  e10 = (v9, v10): w=5,  u=10

  Leaves: v3, v4, v6, v8, v10
  K=1

  Note on paper's w-vector:
    The paper states w = (6,6,4,8,1,4,3,4,5) for edges e2..e10.
    Two discrepancies with Table 1:
      1. w(e3)=6 in vector but g(chi_v3,0,0)=7 in Table 1 => w(e3)=7.
      2. e5/e6 ordering: vector says w(e5)=8,w(e6)=1 but
         g(chi_v6,1,1)=18 requires Dw(e5)=9 => w(e5)=1,w(e6)=8.
    We follow Table 1 values.

Expected results:
  F(T_{v1}, 1) = 13,   S = {v1}

The full per-cell tables (tab-g and tab-f in the manuscript appendix) are
verified and generated by paper_tables.py, which checks EVERY DP cell
against an independent brute-force enumeration and emits the LaTeX
sources.  Running this script also runs that per-cell verification, so a
PASS here means the manuscript tables are reproduced exactly.
"""

import sys
import os
sys.path.insert(0, os.path.dirname(__file__))

from tree import Tree
from mspit_un import solve_mspit_unu, NEG_INF


def build_example1():
    """
    Build the 10-node tree from Example 1.

    Node mapping (0-indexed):
      0=v1, 1=v2, 2=v3, 3=v4, 4=v5, 5=v6, 6=v7, 7=v8, 8=v9, 9=v10

    Edges (undirected, w and u=10 for all), derived from Table 1:
      e2: (v1,v2) = (0,1): w=6, u=10
      e3: (v2,v3) = (1,2): w=7, u=10  [Table 1: g(chi_v3,0,0)=7]
      e4: (v2,v4) = (1,3): w=4, u=10
      e5: (v1,v5) = (0,4): w=1, u=10  [Table 1: g(chi_v6,1,1)=18 -> Dw(e5)=9]
      e6: (v5,v6) = (4,5): w=8, u=10  [w(e5)+w(e6)=9 and Dw(e6)=2]
      e7: (v1,v7) = (0,6): w=4, u=10
      e8: (v7,v8) = (6,7): w=3, u=10
      e9: (v7,v9) = (6,8): w=4, u=10
      e10:(v9,v10)= (8,9): w=5, u=10
    """
    n = 10
    adj = [[] for _ in range(n)]

    def add_edge(u, v, w, uw=10):
        adj[u].append((v, w, uw))
        adj[v].append((u, w, uw))

    # e2: v1-v2 (0-1), w=6
    add_edge(0, 1, 6)
    # e3: v2-v3 (1-2), w=7  (from Table 1)
    add_edge(1, 2, 7)
    # e4: v2-v4 (1-3), w=4
    add_edge(1, 3, 4)
    # e5: v1-v5 (0-4), w=1  (Table 1 implies Dw(e5)=9, so w=1, u=10)
    add_edge(0, 4, 1)
    # e6: v5-v6 (4-5), w=8  (w_sum(chi_v6)=9, and Dw(e6)=2)
    add_edge(4, 5, 8)
    # e7: v1-v7 (0-6), w=4
    add_edge(0, 6, 4)
    # e8: v7-v8 (6-7), w=3
    add_edge(6, 7, 3)
    # e9: v7-v9 (6-8), w=4
    add_edge(6, 8, 4)
    # e10: v9-v10 (8-9), w=5
    add_edge(8, 9, 5)

    return Tree(n=n, adj=adj, root=0)


def run_example1():
    """Run Example 1 and verify results."""
    print("="*70)
    print("EXAMPLE 1 -- 10-node tree, K=1")
    print("Expected: F(T_{v1}, 1) = 13, S = {v1}")
    print("="*70)

    tree = build_example1()

    print("\nTree structure:")
    print(f"  n={tree.n}, root=v1 (index 0)")
    print(f"  Layers: {[f'v{i+1}:{tree.layer[i]}' for i in range(10)]}")
    print(f"  V* = {{v: v in V* (deg>2, not root)}} = "
          f"{[f'v{v+1}' for v in tree.Vstar]}")
    print(f"  Branching nodes V* union {{v1}} = "
          f"{[f'v{v+1}' for v in tree.branching]}")
    print(f"  CD(v1) = {[f'v{v+1}' for v in tree.CD[0]]}")
    print(f"  CD(v2) = {[f'v{v+1}' for v in tree.CD[1]]}")
    print(f"  CD(v7) = {[f'v{v+1}' for v in tree.CD[6]]}")

    print("\nChains:")
    for v_h, chain in sorted(tree.chains.items()):
        print(f"  chi_v{v_h+1}: CA=v{chain.ca+1}, tip=v{v_h+1}, "
              f"beta={chain.beta}, w_sum={chain.w_sum}, delta={chain.delta}")

    K = 1
    opt, S = solve_mspit_unu(tree, K)

    S_names = sorted([f'v{v+1}' for v in S])
    print(f"\nResult: F(T_{{v1}}, {K}) = {opt}")
    print(f"        S = {{{', '.join(S_names)}}}")

    # Verify
    passed = True
    if abs(opt - 13) < 1e-9:
        print("  PASS: Optimal value matches: 13")
    else:
        print(f"  FAIL: Expected 13, got {opt}")
        passed = False

    if S == {0}:
        print("  PASS: Optimal set matches: {v1}")
    else:
        print(f"  FAIL: Expected {{v1}} (index 0), got {S}")
        passed = False

    # Also run a brute-force check
    try:
        from brute import brute_force
        bf_opt, bf_S = brute_force(tree, K)
        print(f"\nBrute-force check: F={bf_opt}, S={{{', '.join(f'v{v+1}' for v in sorted(bf_S))}}}")
        if abs(bf_opt - opt) < 1e-9:
            print("  PASS: Brute force agrees with DP")
        else:
            print(f"  FAIL: Brute force disagrees: BF={bf_opt}, DP={opt}")
            passed = False
    except Exception as e:
        print(f"  (Brute force not available: {e})")

    print("\n" + ("PASS" if passed else "FAIL"))
    return passed


def main():
    print("\n" + "="*70)
    print("REPRODUCING THE WORKED EXAMPLE FROM THE PAPER")
    print("="*70)

    passed = run_example1()

    # Per-cell verification of the appendix tables (tab-g, tab-f):
    # every DP cell is checked against an independent brute force.
    from paper_tables import collect_cells
    tree = build_example1()
    opt, S_opt, g_rows, f_rows, failures = collect_cells(tree, 1)
    print("\nPer-cell table verification (paper_tables.py):")
    print(f"  g-cells: {sum(r['ok'] for r in g_rows)}/{len(g_rows)} verified")
    print(f"  f-cells: {sum(r['ok'] for r in f_rows)}/{len(f_rows)} verified")
    if failures:
        for msg in failures:
            print("  FAIL " + msg)
        passed = False

    return passed


if __name__ == "__main__":
    success = main()
    sys.exit(0 if success else 1)
