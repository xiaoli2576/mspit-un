"""
gen_latex_tables.py -- Generate the two experiment tables of the manuscript
(LaTeX) from an archived experiments JSON, plus the derived ratio sentence.

Usage:
    python gen_latex_tables.py [results/experiments-YYYYMMDD-HHMMSS.json]

Defaults to the newest results/experiments-*.json.  Output goes to
../revision/generated-exptables.tex.  Every number in the manuscript
experiment section must be traceable to the JSON named in the output header.
"""

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "revision", "generated-exptables.tex")


def fmt(x):
    return f"{x:.4f}"


def main():
    if len(sys.argv) > 1:
        jpath = sys.argv[1]
    else:
        cands = sorted(glob.glob(os.path.join(HERE, "results",
                                              "experiments-*.json")))
        if not cands:
            print("no results/experiments-*.json found"); return 1
        jpath = cands[-1]
    with open(jpath, encoding="utf-8") as fh:
        data = json.load(fh)

    sizes = [r["n"] for r in data["mspit"]]
    t1 = {r["n"]: r for r in data["mspit"]}
    t2 = {r["n"]: r for r in data["mcspit"]}

    ratios = {n: t2[n]["avg"] / t1[n]["avg"] for n in sizes}
    rmin, rmax = min(ratios.values()), max(ratios.values())

    L = []
    L.append("% ------------------------------------------------------")
    L.append("% AUTO-GENERATED by code/gen_latex_tables.py -- do not edit.")
    L.append(f"% Source: {os.path.basename(jpath)}")
    L.append(f"% Platform: {data['platform']}, Python {data['python']}")
    L.append("% ------------------------------------------------------")
    L.append("")
    # ---- Table 1: random recursive trees ----
    L.append(r"\begin{table}[!htbp]")
    L.append(r"\centering")
    L.append(r"\caption{Running time (seconds) of Algorithms~\ref{alg-mspitun} "
             r"and~\ref{alg-mcspitun}. Algorithm~\ref{alg-mspitun} is evaluated "
             r"with $K=\lceil 0.3n\rceil$. Algorithm~\ref{alg-mcspitun} is "
             r"evaluated with $D:=0.7\,F(T_{v_1},n)$, that is, $70\%$ of the "
             r"all-upgraded optimum shortest root-leaf distance.}")
    L.append(r"\label{tab-experiments}")
    L.append(r"\begin{tabular}{lrrrrrrr}")
    L.append(r"\toprule")
    L.append("Bound & $n$ & " + " & ".join(str(n) for n in sizes) + r" \\")
    L.append(r"\midrule")
    L.append(r"$O(n^3)$       & $T_1$ (avg)  & "
             + " & ".join(fmt(t1[n]["avg"]) for n in sizes) + r" \\")
    L.append(r"               & $T_1$ (min)  & "
             + " & ".join(fmt(t1[n]["min"]) for n in sizes) + r" \\")
    L.append(r"               & $T_1$ (max)  & "
             + " & ".join(fmt(t1[n]["max"]) for n in sizes) + r" \\")
    L.append(r"\midrule")
    L.append(r"$O(n^3\log n)$ & $T_2$ (avg)  & "
             + " & ".join(fmt(t2[n]["avg"]) for n in sizes) + r" \\")
    L.append(r"               & $T_2$ (min)  & "
             + " & ".join(fmt(t2[n]["min"]) for n in sizes) + r" \\")
    L.append(r"               & $T_2$ (max)  & "
             + " & ".join(fmt(t2[n]["max"]) for n in sizes) + r" \\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    L.append(r"\end{table}")
    L.append("")
    # ---- Table 2: structured stress tests ----
    fams = data["structured"]
    ns = [row["n"] for row in fams[0]["rows"]]
    L.append(r"\begin{table}[!htbp]")
    L.append(r"\centering")
    L.append(r"\caption{Structured stress tests for "
             r"Algorithm~\ref{alg-mspitun}. Each entry is the running time "
             r"in seconds on one deterministic instance with "
             r"$K=\lceil0.3n\rceil$.}")
    L.append(r"\label{tab-structured-experiments}")
    L.append(r"\begin{tabular}{l" + "r" * len(ns) + "}")
    L.append(r"\toprule")
    L.append("Tree family & " + " & ".join(f"$n={n}$" for n in ns) + r" \\")
    L.append(r"\midrule")
    for fam in fams:
        name = fam["family"].replace("Layered 4-ary", r"Layered $4$-ary")
        L.append(name + " & "
                 + " & ".join(fmt(r["time"]) for r in fam["rows"]) + r" \\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    L.append(r"\end{table}")
    L.append("")
    L.append("% ---- derived numbers for the discussion paragraph ----")
    L.append(f"% MCSPIT/MSPIT avg-time ratios by n: "
             + ", ".join(f"n={n}: {ratios[n]:.2f}" for n in sizes))
    L.append(f"% ratio range: between {rmin:.2f} and {rmax:.2f}")
    L.append("% Suggested sentence: `while the binary-search wrapper was "
             f"between ${rmin:.2f}$ and ${rmax:.2f}$ times the cost of a "
             "single base-DP call (ratios computed from the unrounded "
             "timings)'")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"LaTeX written: {os.path.normpath(OUT)}")
    print(f"ratio range: {rmin:.2f} .. {rmax:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
